/**
 * 全站图标总表：通用 UI + 货物 + 载具/海盗。
 * 三个来源共用一套 name 空间，重名会在 TS 层面被发现（key 冲突时后者覆盖，
 * 因此新增图标请先搜一遍已有命名）。
 */
export const GLYPH_PATHS = { ...UI_PATHS, ...GOOD_PATHS, ...FIGURE_PATHS }

export type GlyphName = keyof typeof GLYPH_PATHS

interface Props {
  name: GlyphName
  /** 边长（px），默认 18 */
  size?: number
  /** 描边宽度，默认 1.7；大图可加粗，小尺寸可减细 */
  strokeWidth?: number
  color?: string
  className?: string
  style?: CSSProperties
  title?: string
}

/** 按名渲染图标：优先使用 AI 全彩位图（public/icons/<name>.png），
 *  位图缺失（如尚未补充的 check / arrowRight 等）时回落到内置 SVG 描边。 */
export function Glyph({ name, size = 18, strokeWidth = 1.7, color, className, style, title }: Props) {
  const [failed, setFailed] = useState(false)
  if (!failed) {
    return (
      <ArtIcon
        name={name}
        size={size}
        className={className}
        style={style}
        onError={() => setFailed(true)}
      />
    )
  }
  const paths = GLYPH_PATHS[name] ?? GLYPH_PATHS.help
  return (
    <svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      className={className}
      style={{
        display: 'inline-block',
        verticalAlign: '-0.15em',
        flexShrink: 0,
        color,
        ...style,
      }}
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden={title ? undefined : true}
      role={title ? 'img' : undefined}
    >
      {title ? <title>{title}</title> : null}
      {paths.map((d, i) => <path key={i} d={d} />)}
    </svg>
  )
}

/** Canvas 用：把图标描边到 2D 上下文（分享图也走矢量，不再依赖 emoji 字形） */
export function drawGlyph(
  ctx: CanvasRenderingContext2D,
  name: GlyphName,
  x: number,
  y: number,
  size: number,
  color: string,
  lineWidth = 1.7,
) {
  const paths = GLYPH_PATHS[name]
  if (!paths) return
  const k = size / 24
  ctx.save()
  ctx.translate(x, y)
  ctx.scale(k, k)
  ctx.strokeStyle = color
  ctx.lineWidth = lineWidth
  ctx.lineCap = 'round'
  ctx.lineJoin = 'round'
  for (const d of paths) ctx.stroke(new Path2D(d))
  ctx.restore()
}
